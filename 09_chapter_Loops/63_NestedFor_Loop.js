// Nested For Loop
for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
        console.log(`i = ${i}, j = ${j}`);
    }
}


//For example, the outer loop runs 3 times (i = 0, 1, 2), and for each iteration of the outer loop, the inner loop also runs 3 times (j = 0, 1, 2). This results in a total of 9 iterations, and the console will log the values of i and j for each combination.
for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
        console.log(`i = ${i}, j = ${j}`);
    }
}
